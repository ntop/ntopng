local other_alert_keys = require "other_alert_keys"

-- Import the classes library.
local classes = require "classes"
-- Make sure to import the Superclass!
local alert = require "alert"
local alert_entities = require "alert_entities"
local format_utils = require "format_utils"
-- Import Mitre Att&ck utils
local mitre = require "mitre_utils"

-- ##############################################

local alert_dhcp_storm = classes.class(alert)

-- ##############################################

alert_dhcp_storm.meta = {
  alert_key = other_alert_keys.alert_dhcp_storm,
  i18n_title = "alerts_dashboard.dhcp_storm",
  icon = "fas fa-fw fa-ghost",
  entities = {
     alert_entities.interface,
  },
  issue_resolve_policy = "manual", -- Attack: the issue is resolved by the user only

   -- Mitre Att&ck Matrix values
   mitre_values = {
      mitre_tactic = mitre.tactic.credential_access,
      mitre_technique = mitre.technique.adversary_in_the_middle,
      mitre_sub_technique = mitre.sub_technique.dhcp_spoofing,
      mitre_id = "T1557.003"
   },
}

-- ##############################################

-- @brief Prepare an alert table used to generate the alert
-- @param dhcp_info The counters of the second that exceeded the threshold, as
--        queued by NetworkInterface::checkDHCPStorm
-- @return A table with the alert built
function alert_dhcp_storm:init(dhcp_info)
   -- Call the parent constructor
   self.super:init()

   self.alert_type_params = dhcp_info
end

-- #######################################################

-- @brief Format an alert into a human-readable string
-- @param ifid The integer interface id of the generated alert
-- @param alert The alert description table, including alert data such as the generating entity, timestamp, granularity, type
-- @param alert_type_params Table `alert_type_params` as built in the `:init` method
-- @return A human-readable string
function alert_dhcp_storm.format(ifid, alert, alert_type_params)
   -- dhcp_num_pkts: alerts generated by older versions
   local num_pkts = tonumber(alert_type_params.num_pkts or alert_type_params.dhcp_num_pkts) or 0
   local num_requests = alert_type_params.num_requests or 0
   local num_replies = alert_type_params.num_replies or 0
   local num_client_macs = alert_type_params.num_client_macs or 0
   local sender_pkts = alert_type_params.sender_pkts or 0

   -- No requests/replies for collected flows (not exported) and older alerts
   local msg

   if num_requests + num_replies > 0 then
      msg = i18n("alerts_dashboard.dhcp_storm_requests_replies", {
         num_requests = format_utils.formatValue(num_requests),
         num_replies = format_utils.formatValue(num_replies),
      })
   else
      msg = i18n("alerts_dashboard.dhcp_storm_packets", {
         dhcp_num_pkts = format_utils.formatValue(num_pkts),
      })
   end

   if num_client_macs > 0 then
      msg = msg .. ", " .. i18n("alerts_dashboard.dhcp_storm_client_macs", {
         num_client_macs = format_utils.formatValue(num_client_macs),
      })
   end

   if not isEmptyString(alert_type_params.sender_mac) then
      local sender = alert_type_params.sender_mac
      local vlan_id = tonumber(alert_type_params.sender_vlan_id) or 0

      if not isEmptyString(alert_type_params.sender_ip) then
         sender = sender .. " " .. alert_type_params.sender_ip
      end

      if vlan_id ~= 0 then
         sender = sender .. " " .. i18n("vlan") .. " " .. vlan_id
      end

      msg = msg .. ". " .. i18n("alerts_dashboard.dhcp_storm_main_sender", {
         sender = sender,
         sender_pkts = format_utils.formatValue(sender_pkts),
         pct = math.floor(sender_pkts * 100 / num_pkts),
      })
   elseif alert_type_params.sender_mac then
      msg = msg .. ". " .. i18n("alerts_dashboard.dhcp_storm_no_main_sender")
   end

   return msg
end

-- #######################################################

return alert_dhcp_storm
